func EnabledFor(warehouse, zone string) []Policy {
	out := []Policy{}
	for _, p := range Policies {
		if p.Enabled && p.Warehouse == warehouse && p.Zone == zone {
			out = append(out, p)
		}
	}
	return out
}
func RouteFor(warehouse, zone string) string {
	a := EnabledFor(warehouse, zone)
	if len(a) == 0 {
		return ""
	}
	best := a[0]
	for _, p := range a[1:] {
		if p.Priority > best.Priority {
			best = p
		}
	}
	return best.Route
}
func CountEnabled() int {
	n := 0
	for _, p := range Policies {
		if p.Enabled {
			n++
		}
	}
	return n
}
